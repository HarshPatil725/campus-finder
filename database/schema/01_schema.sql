-- Campus Wi-Fi Monitoring and Incident Management System
-- Schema Definition

-- 1. ACCESS POINTS TABLE
CREATE TABLE IF NOT EXISTS access_points (
    access_point_id TEXT PRIMARY KEY,
    building TEXT NOT NULL,
    location TEXT NOT NULL
);

-- 2. NETWORK READINGS TABLE
CREATE TABLE IF NOT EXISTS network_readings (
    reading_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    access_point_id TEXT NOT NULL REFERENCES access_points(access_point_id) ON DELETE RESTRICT,
    timestamp TIMESTAMP NOT NULL,
    latency_ms NUMERIC NULL,
    packet_loss_pct NUMERIC NOT NULL,
    is_up BOOLEAN NOT NULL,
    CONSTRAINT chk_network_readings_packet_loss CHECK (packet_loss_pct >= 0 AND packet_loss_pct <= 100),
    CONSTRAINT chk_network_readings_latency CHECK (latency_ms IS NULL OR latency_ms >= 0)
);

-- 3. INCIDENTS TABLE
CREATE TABLE IF NOT EXISTS incidents (
    incident_id TEXT PRIMARY KEY,
    access_point_id TEXT NOT NULL REFERENCES access_points(access_point_id) ON DELETE RESTRICT,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NULL,
    status TEXT NOT NULL,
    suspected_cause TEXT NOT NULL,
    resolution TEXT NULL,
    CONSTRAINT chk_incidents_status CHECK (status IN ('Open', 'Investigating', 'Resolved')),
    CONSTRAINT chk_incidents_time_order CHECK (end_time IS NULL OR end_time >= start_time),
    CONSTRAINT chk_incidents_resolved_details CHECK (
        status != 'Resolved' OR (end_time IS NOT NULL AND resolution IS NOT NULL)
    )
);

-- INDEXES
CREATE INDEX IF NOT EXISTS idx_network_readings_ap_id ON network_readings(access_point_id);
CREATE INDEX IF NOT EXISTS idx_network_readings_timestamp ON network_readings(timestamp);
CREATE INDEX IF NOT EXISTS idx_network_readings_ap_timestamp ON network_readings(access_point_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_incidents_ap_id ON incidents(access_point_id);
CREATE INDEX IF NOT EXISTS idx_incidents_status ON incidents(status);
CREATE INDEX IF NOT EXISTS idx_incidents_start_time ON incidents(start_time);

-- 4. VIEW: v_network_readings_with_health
CREATE OR REPLACE VIEW v_network_readings_with_health AS
SELECT
    reading_id,
    access_point_id,
    timestamp,
    latency_ms,
    packet_loss_pct,
    is_up,
    CASE
        WHEN is_up = false THEN 'Down'
        WHEN is_up = true AND latency_ms < 250 AND packet_loss_pct < 20 THEN 'Healthy'
        WHEN is_up = true AND (latency_ms >= 250 OR packet_loss_pct >= 20) THEN 'Degraded'
        ELSE 'Unknown'
    END AS health_status
FROM network_readings;

-- 5. VIEW: v_latest_access_point_status
CREATE OR REPLACE VIEW v_latest_access_point_status AS
SELECT DISTINCT ON (ap.access_point_id)
    ap.access_point_id,
    ap.building,
    ap.location,
    r.reading_id,
    r.timestamp AS latest_reading_timestamp,
    r.latency_ms AS latest_latency_ms,
    r.packet_loss_pct AS latest_packet_loss_pct,
    r.is_up AS latest_is_up,
    r.health_status AS current_status
FROM access_points ap
LEFT JOIN v_network_readings_with_health r ON ap.access_point_id = r.access_point_id
ORDER BY ap.access_point_id, r.timestamp DESC NULLS LAST, r.reading_id DESC NULLS LAST;
